"""Generate signing/payload test vectors from FinSentinel's OWN code.

Every client implementation (fldemo.wire in Python, the ESP32 C++ firmware)
must reproduce these bytes exactly. The private key here is a fixed,
publicly-known TEST key (seed = 32 bytes of 0x01) — never used at runtime.

Usage:  demo/.venv/Scripts/python demo/scripts/gen_test_vectors.py
"""

from __future__ import annotations

import base64
import hashlib
import json
import sys
from pathlib import Path

DEMO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(DEMO))
sys.path.insert(0, str(DEMO.parent / "finsentinel"))

import numpy as np  # noqa: E402
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey  # noqa: E402
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat  # noqa: E402

from core.crypto import canonical_signed_data, sign_envelope, verify_envelope_signature  # noqa: E402
from ingestion.schemas import UpdateEnvelope  # noqa: E402
from ingestion.serialization import deserialize_state_dict  # noqa: E402

from fldemo import MODEL_VERSION  # noqa: E402
from fldemo.model import TENSOR_SPECS  # noqa: E402
from fldemo.testvectors import deterministic_state  # noqa: E402
from fldemo.wire import build_npz_stored  # noqa: E402

OUT = DEMO / "tests" / "vectors" / "finsentinel_vectors.json"
TEST_SEED = bytes([1]) * 32


def main() -> None:
    key = Ed25519PrivateKey.from_private_bytes(TEST_SEED)
    pub = key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)

    state = deterministic_state()
    payload = build_npz_stored(state)
    restored = deserialize_state_dict(payload)  # FinSentinel's deserializer must accept STORED zips
    assert list(restored) == [n for n, _ in TENSOR_SPECS]
    for name in state:
        assert np.array_equal(restored[name].numpy(), state[name])

    vectors = []
    for created_at in (
        "2026-11-22T10:15:30Z",          # the form devices send
        "2026-11-22T15:45:30+05:30",     # same instant, IST offset → normalised to UTC
        "2026-11-22T10:15:30.250000Z",   # sub-second precision is kept by the server
    ):
        env = UpdateEnvelope(
            update_id="esp32-01-r0001-a1b2c3",
            client_id="esp32-01",
            model_version=MODEL_VERSION,
            round_number=1,
            sample_count=341,
            payload_sha256=hashlib.sha256(payload).hexdigest(),
            payload_size_bytes=len(payload),
            created_at=created_at,
            signature="placeholder",
            signing_key_id="esp32-01-key",
        )
        signed = canonical_signed_data(env)
        sig = sign_envelope(env, key)
        env = env.model_copy(update={"signature": sig})
        assert verify_envelope_signature(env, key.public_key())
        vectors.append({
            "created_at_sent": created_at,
            "canonical_signed_data": signed.decode("utf-8"),
            "signature_base64": sig,
        })

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({
        "_doc": "Generated by demo/scripts/gen_test_vectors.py from FinSentinel's core.crypto, "
                "ingestion.schemas and ingestion.serialization. TEST KEY ONLY (seed 0x01*32).",
        "test_private_seed_hex": TEST_SEED.hex(),
        "test_public_key_hex": pub.hex(),
        "payload": {
            "description": "build_npz_stored(deterministic_state()) — STORED zip; "
                           "values (i mod 97 - 48)/64 over the flattened tensors in TENSOR_SPECS order",
            "sha256": hashlib.sha256(payload).hexdigest(),
            "size_bytes": len(payload),
            "base64": base64.b64encode(payload).decode("ascii"),
        },
        "envelopes": vectors,
    }, indent=1))
    print("wrote", OUT, "payload", len(payload), "bytes")

    # C header for the Wokwi probe / firmware tests (TEST key — public, safe to commit).
    def c_bytes(b: bytes) -> str:
        return ", ".join(f"0x{x:02x}" for x in b)

    v0 = vectors[0]
    canon = v0["canonical_signed_data"].replace("\\", "\\\\").replace('"', '\\"')
    header = (
        "// GENERATED by demo/scripts/gen_test_vectors.py from FinSentinel's own code.\n"
        "// TEST KEY ONLY (seed = 32 x 0x01) — publicly known, never used at runtime.\n"
        "#pragma once\n#include <stdint.h>\n"
        f"static const uint8_t TV_SEED[32] = {{{c_bytes(TEST_SEED)}}};\n"
        f"static const uint8_t TV_PUBKEY[32] = {{{c_bytes(pub)}}};\n"
        f"static const uint8_t TV_SIGNATURE[64] = {{{c_bytes(base64.b64decode(v0['signature_base64']))}}};\n"
        f'static const char TV_CANONICAL[] = "{canon}";\n'
    )
    hdr = DEMO / "wokwi" / "probe" / "vector.h"
    hdr.write_text(header)
    print("wrote", hdr)
    for v in vectors:
        print(v["created_at_sent"], "->", v["canonical_signed_data"][:120], "...")


if __name__ == "__main__":
    main()
