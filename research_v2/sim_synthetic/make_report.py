"""Turn Stage-0 JSON results into research_v2/STAGE0_RESULTS.md tables (reproducible; no hand-edited numbers)."""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
main = json.loads((HERE / "results_stage0.json").read_text())
thr = json.loads((HERE / "results_stage0_threshold.json").read_text())
# threshold cells in the main file were invalid (bug: ran as MCAR) -> replace with the corrected run
cells = [c for c in main["cells"] if c["mech"] != "threshold"] + thr["cells"]
order = {"mcar": 0, "mnar": 1, "threshold": 2}
cells.sort(key=lambda c: (c["rho"], order[c["mech"]], c["beta"]))

M = ["fedavg", "ipw_oracle_hajek", "ipw_ema", "lag_mar", "fdms_sub", "dsdr", "dsdr_nogate", "dsdr_ipw", "dsdr_oraclepi"]
LABEL = {"fedavg": "FedAvg", "ipw_oracle_hajek": "IPW (oracle π)", "ipw_ema": "FedIPW-EMA", "lag_mar": "lag-MAR (A3)",
         "fdms_sub": "FL-FDMS-sub", "dsdr": "**DS-DR**", "dsdr_nogate": "DS-DR no gate", "dsdr_ipw": "DS-DR m≡0",
         "dsdr_oraclepi": "DS-DR oracle π"}


def name(c):
    return {"mcar": "MCAR", "threshold": "MNAR-threshold"}.get(c["mech"], f"MNAR β={int(c['beta'])}")


def table(key, fmt="%.3f", se_key=None):
    rows = ["| ρ_S | mechanism | " + " | ".join(LABEL[m] for m in M) + " |",
            "|---|---|" + "---|" * len(M)]
    for c in cells:
        vals = []
        for m in M:
            v = c["methods"][m][key]
            s = fmt % v
            if se_key:
                s += " ±%.2f" % (1.96 * c["methods"][m][se_key])
            vals.append(s)
        rows.append(f"| {c['rho']} | {name(c)} | " + " | ".join(vals) + " |")
    return "\n".join(rows)


def diag_table():
    rows = ["| ρ_S | mechanism | gate open | corr(π̂,π) DS-DR GMM | FedIPW-EMA | lag-MAR | mean cap λ |", "|---|---|---|---|---|---|---|"]
    for c in cells:
        d = c["diag"]
        f = lambda v: "–" if v is None else "%.3f" % v
        rows.append(f"| {c['rho']} | {name(c)} | {f(d['gate_open_rate'])} | {f(d['corr_gmm'])} | {f(d['corr_ema'])} | "
                    f"{f(d['corr_lagmar'])} | {f(d['lambda'])} |")
    return "\n".join(rows)


design = main["design"]
